// This file is the plumbing of the slow rig: a world (an origin served over plain HTTP and a replica
// served by the shared TLS front end, both in front of stock `git http-backend`), a site (one mirror
// plus one replica repository) that runs the REAL syncRepo, and the recording around it.

// rigFrontStats describes the receive-pack POST requests one git call made to a replica front.
type rigFrontStats struct {
	Posts       int   // requests that carried a push
	MaxBody     int64 // the largest request body, in bytes
	Chunked     bool  // some request carried no Content-Length
	LimitStatus int   // requests the body limit answered 413
}

// frontStatsSince summarises the push requests the front recorded after the first mark.
func frontStatsSince(f *replicaFront, mark int) rigFrontStats {
	var st rigFrontStats
	reqs := f.Requests()
	for _, r := range reqs[min(mark, len(reqs)):] {
		if !r.Push {
			continue
		}
		st.Posts++
		st.MaxBody = max(st.MaxBody, r.Bytes)
		st.Chunked = st.Chunked || r.Chunked
		if r.Status == http.StatusRequestEntityTooLarge {
			st.LimitStatus++
		}
	}
	return st
}

// rigLogBuffer is a bytes.Buffer safe to share with a logger.
type rigLogBuffer struct {
	mu sync.Mutex
	b  bytes.Buffer
}

func (l *rigLogBuffer) Write(p []byte) (int, error) {
	l.mu.Lock()
	defer l.mu.Unlock()
	return l.b.Write(p)
}

func (l *rigLogBuffer) String() string {
	l.mu.Lock()
	defer l.mu.Unlock()
	return l.b.String()
}

// rigReport prints the rig's lines to the test log and checks every one for a credential.
type rigReport struct {
	t       *testing.T
	secrets []string
}

// sum prints one summary line (RIG-SUMMARY), key=value pairs after the scenario name.
func (r *rigReport) sum(scenario string, kv ...any) {
	var b strings.Builder
	b.WriteString("RIG-SUMMARY scenario=" + scenario)
	for i := 0; i+1 < len(kv); i += 2 {
		fmt.Fprintf(&b, " %v=%v", kv[i], kv[i+1])
	}
	r.emit(b.String())
}

func (r *rigReport) note(format string, args ...any) {
	r.emit("RIG " + fmt.Sprintf(format, args...))
}

func (r *rigReport) emit(s string) {
	r.t.Helper()
	rigNoSecrets(r.t, "rig output", s, r.secrets...)
	r.t.Log(s)
}

// rigWorld is one scenario's servers and directories.
type rigWorld struct {
	t         *testing.T
	root      string
	originDir string // the origin repository on disk; generated by the scenario
	origin    *gitHTTPServer
	report    *rigReport
}

// rigPrepare skips the test when the rig cannot run here, and stops it early when the test binary's
// remaining time is too short for the scenario (go test's default 10m would kill it half way).
func rigPrepare(t *testing.T, need time.Duration) {
	t.Helper()
	if ok, detail := GitVersionOK(); !ok {
		t.Skipf("rig needs git >= 2.31: %s", detail)
	}
	backend := filepath.Join(strings.TrimSpace(git(t, "", "--exec-path")), "git-http-backend")
	if _, err := os.Stat(backend); err != nil {
		t.Skipf("rig needs git-http-backend: %v", err)
	}
	if need := rigDiskNeeded(t); need > 0 {
		var fs syscall.Statfs_t
		if err := syscall.Statfs(os.TempDir(), &fs); err == nil && int64(fs.Bavail)*int64(fs.Bsize) < need {
			t.Fatalf("%s has %.1f GiB free and this run needs about %.1f GiB: lower RIG_LARGE_MIB or point TMPDIR elsewhere",
				os.TempDir(), float64(int64(fs.Bavail)*int64(fs.Bsize))/(1<<30), float64(need)/(1<<30))
		}
	}
	if d, ok := t.Deadline(); ok && time.Until(d) < need {
		t.Fatalf("only %v of the test timeout is left and this scenario needs about %v: run with -timeout 60m", time.Until(d).Round(time.Second), need)
	}
}

func newRigWorld(t *testing.T) *rigWorld {
	t.Helper()
	root := t.TempDir()
	if keep := os.Getenv("RIG_KEEP"); keep != "" {
		dir, err := os.MkdirTemp("", "rig-keep-")
		if err != nil {
			t.Fatal(err)
		}
		root = dir
		t.Logf("RIG_KEEP: directories kept under %s", root)
	}
	w := &rigWorld{t: t, root: root, originDir: filepath.Join(root, "o", "origin.git")}
	w.report = &rigReport{t: t, secrets: []string{httpOriginToken}}

	// Whatever the connector logs while it runs is checked for a credential at the end.
	var logs rigLogBuffer
	prev := slog.Default()
	slog.SetDefault(slog.New(slog.NewTextHandler(&logs, &slog.HandlerOptions{Level: slog.LevelDebug})))
	t.Cleanup(func() {
		slog.SetDefault(prev)
		rigNoSecrets(t, "connector log output", logs.String(), w.report.secrets...)
	})

	w.origin = newGitHTTPServer(t, filepath.Join(root, "o"), "Bearer "+httpOriginToken, http.StatusUnauthorized)

	name := t.Name()
	t.Cleanup(func() {
		verdict := "PASS"
		if t.Failed() {
			verdict = "FAIL"
		}
		t.Logf("RIG-RESULT %s %s", name, verdict)
	})
	return w
}

// rigLimits builds the effective limits through ResolveLimits, from the wire values, so the rig runs
// with exactly what a platform-supplied configuration would produce (and its validation). A zero
// argument is left unset.
func rigLimits(t *testing.T, batchRefs, pushTimeoutSecs, maxRepoMB int) Limits {
	t.Helper()
	var l proto.GitSyncLimits
	set := func(dst **int, v int) {
		if v > 0 {
			*dst = &v
		}
	}
	set(&l.PushBatchRefs, batchRefs)
	set(&l.PushTimeoutSeconds, pushTimeoutSecs)
	set(&l.MaxRepositoryMB, maxRepoMB)
	lim, err := ResolveLimits(nil, &l)
	if err != nil {
		t.Fatalf("ResolveLimits: %v", err)
	}
	return lim
}

// rigSite is one mirror and one replica repository.
type rigSite struct {
	w          *rigWorld
	mirrorRoot string
	replicaDir string
	front      *replicaFront // the TLS front end of this site's replica
	task       syncTask
}

const rigRepoID = "rig-repo"

// rigNoBodyLimit is a request-body limit no push reaches: the front buffers the request but never refuses it.
const rigNoBodyLimit = 1 << 40

// site returns the site whose replica repository is replica and whose mirror lives under mirror.
// Two sites that share a mirror name share the mirror.
func (w *rigWorld) site(replica, mirror string) *rigSite {
	w.t.Helper()
	s := &rigSite{w: w, mirrorRoot: filepath.Join(w.root, "m", mirror), replicaDir: filepath.Join(w.root, "r", replica+".git")}
	git(w.t, "", "init", "--bare", "-b", "main", s.replicaDir)
	s.front = newReplicaFront(w.t, s.replicaDir)
	// The front buffers a push in full before it forwards it (CGI cannot take a chunked body) and, with
	// no body limit, refuses one over 64 MiB. A large push needs a limit that never applies instead.
	s.front.SetMaxBody(rigNoBodyLimit)
	w.report.secrets = append(w.report.secrets, s.front.KnownTokens()...)
	s.task = syncTask{
		RepoID:       rigRepoID,
		CanonicalURL: w.origin.URL + "/origin.git",
		Origin:       LocalEntry{BaseURL: w.origin.URL, Auth: "bearer", Token: Secret(httpOriginToken)},
		ReplicaURL:   s.front.ReplicaURL(),
		PushToken:    Secret(s.front.Token()),
	}
	return s
}

func (s *rigSite) mirrorDir() string { return (Mirrors{Root: s.mirrorRoot}).Dir(rigRepoID) }

// restore replaces the site's replica and mirror with copies of the given directories.
func (s *rigSite) restore(replicaFrom, mirrorFrom string) {
	t := s.w.t
	t.Helper()
	for _, c := range []struct{ dst, src string }{{s.replicaDir, replicaFrom}, {s.mirrorRoot, mirrorFrom}} {
		if err := os.RemoveAll(c.dst); err != nil {
			t.Fatal(err)
		}
		if err := os.CopyFS(c.dst, os.DirFS(c.src)); err != nil {
			t.Fatalf("copy %s: %v", filepath.Base(c.src), err)
		}
	}
}

// snapshot copies the site's replica and mirror to a directory of its own and returns the two paths.
func (s *rigSite) snapshot(name string) (replica, mirror string) {
	t := s.w.t
	t.Helper()
	base := filepath.Join(s.w.root, "snap", name)
	replica, mirror = filepath.Join(base, "replica"), filepath.Join(base, "mirror")
	for _, c := range []struct{ dst, src string }{{replica, s.replicaDir}, {mirror, s.mirrorRoot}} {
		if err := os.CopyFS(c.dst, os.DirFS(c.src)); err != nil {
			t.Fatalf("snapshot %s: %v", name, err)
		}
	}
	return replica, mirror
}

// rigCall is one git invocation of a sync.
type rigCall struct {
	kind   string // fetch, plan, batch, final, or other
	dur    time.Duration
	err    error
	prune  bool
	specs  []string // refspecs after the replica URL, for pushes
	front  rigFrontStats
	isPush bool
}

// rigKind names what an argv is: the fetch, a push's role (plan = --dry-run, batch = explicit
// refspecs, final = --prune), or other.
func rigKind(argv []string) string {
	switch (gitCall{argv: argv}).sub() {
	case "fetch":
		return "fetch"
	case "push":
		switch {
		case slices.Contains(argv, "--dry-run"):
			return "plan"
		case slices.Contains(argv, "--prune"):
			return "final"
		}
		return "batch"
	}
	return "other"
}

// rigRecorder wraps the real git runner: it times every call, reads the front end's statistics for
// each push, and lets a scenario act after a push finished.
type rigRecorder struct {
	report *rigReport
	front  *replicaFront

	mu    sync.Mutex
	calls []rigCall
	// after, when set, runs after each push that succeeded, with how many pushes have finished.
	after func(c rigCall, pushes int)
}

func (r *rigRecorder) runOut(ctx context.Context, argv, env []string, dir string, w io.Writer) ([]byte, error) {
	kind := rigKind(argv)
	push := kind == "plan" || kind == "batch" || kind == "final"
	mark := len(r.front.Requests())
	start := time.Now()
	stderr, err := runGitOut(ctx, argv, env, dir, w)
	c := rigCall{kind: kind, dur: time.Since(start), err: err, isPush: push, prune: slices.Contains(argv, "--prune")}
	if push {
		c.front = frontStatsSince(r.front, mark)
		if kind != "plan" {
			c.specs = slices.Clone(refspecsOf(gitCall{argv: argv}))
		}
	}
	// Raw git output, before the connector's own redaction sees it: git itself must not print a token.
	rigNoSecrets(r.report.t, "git stderr", string(stderr), r.report.secrets...)

	r.mu.Lock()
	r.calls = append(r.calls, c)
	pushes := 0
	for _, p := range r.calls {
		if p.isPush {
			pushes++
		}
	}
	r.mu.Unlock()
	if push && err == nil && r.after != nil {
		r.after(c, pushes)
	}
	return stderr, err
}

func (r *rigRecorder) run(ctx context.Context, argv, env []string, dir string) ([]byte, error) {
	return r.runOut(ctx, argv, env, dir, io.Discard)
}

// rigOutcome is what one sync did.
type rigOutcome struct {
	res     syncResult
	elapsed time.Duration
	calls   []rigCall
	peakMiB float64 // the mirror's largest size seen while the sync ran
	rssMiB  float64 // the largest resident set of a connector git process tree; 0 when not measured
}

func (o rigOutcome) count(kind string) int {
	n := 0
	for _, c := range o.calls {
		if c.kind == kind {
			n++
		}
	}
	return n
}

// dur is the total time the calls of a kind took.
func (o rigOutcome) dur(kind string) time.Duration {
	var d time.Duration
	for _, c := range o.calls {
		if c.kind == kind {
			d += c.dur
		}
	}
	return d
}

// push returns the calls that were pushes, in order.
func (o rigOutcome) pushes() []rigCall {
	var out []rigCall
	for _, c := range o.calls {
		if c.isPush {
			out = append(out, c)
		}
	}
	return out
}

// seq renders the pushes of the sync in order, runs of a kind folded: "plan,batch*4,final".
func (o rigOutcome) seq() string {
	var parts []string
	for i := 0; i < len(o.calls); {
		if !o.calls[i].isPush {
			i++
			continue
		}
		j := i
		for j < len(o.calls) && o.calls[j].isPush && o.calls[j].kind == o.calls[i].kind {
			j++
		}
		if n := j - i; n > 1 {
			parts = append(parts, fmt.Sprintf("%s*%d", o.calls[i].kind, n))
		} else {
			parts = append(parts, o.calls[i].kind)
		}
		i = j
	}
	return strings.Join(parts, ",")
}

func (o rigOutcome) refsPushed() int {
	if o.res.Stats.RefsPushed == nil {
		return -1
	}
	return *o.res.Stats.RefsPushed
}

func (o rigOutcome) verdict() string {
	if o.res.State == StateOK {
		return "ok"
	}
	return o.res.State + "/" + o.res.ErrorType
}

type rigSyncOpts struct {
	timeout time.Duration // zero means 40 minutes
	rss     *rigRSS       // when set, the connector's git processes are measured
	after   func(c rigCall, pushes int)
}

// sync runs one real syncRepo for the site under lim.
func (s *rigSite) sync(lim Limits, o rigSyncOpts) rigOutcome {
	t := s.w.t
	t.Helper()
	if o.timeout == 0 {
		o.timeout = 40 * time.Minute
	}
	rec := &rigRecorder{report: s.w.report, front: s.front, after: o.after}
	deps := syncDeps{
		limits:  func() Limits { return lim },
		mirrors: Mirrors{Root: s.mirrorRoot},
		run:     s.front.trustRun(rec.run),
		runOut:  s.front.trustRunOut(rec.runOut),
		now:     time.Now,
	}
	ctx, cancel := context.WithTimeout(context.Background(), o.timeout)
	defer cancel()

	sampler := startPeakSampler(s.mirrorDir(), time.Second)
	defer sampler.Stop() // a failing hook ends the test from inside syncRepo: nothing may be left running
	var endRSS func() int64
	if o.rss != nil {
		endRSS = o.rss.begin()
		defer endRSS()
	}
	start := time.Now()
	res := syncRepo(ctx, deps, s.task)
	elapsed := time.Since(start)
	out := rigOutcome{res: res, elapsed: elapsed, calls: rec.calls, peakMiB: mib(sampler.Stop())}
	if endRSS != nil {
		out.rssMiB = mib(endRSS())
	}
	rigNoSecrets(t, "sync result", fmt.Sprintf("%+v", res), s.w.report.secrets...)
	return out
}

// mustBeOK fails the test unless the sync succeeded.
func (o rigOutcome) mustBeOK(t *testing.T, what string) {
	t.Helper()
	if o.res.State != StateOK {
		t.Fatalf("%s: sync = %s (detail %q), want ok", what, o.verdict(), o.res.ErrorDetail)
	}
}

// requireReplicaMatches fails unless the replica's branches and tags are exactly the origin's.
func (s *rigSite) requireReplicaMatches(want map[string]string, what string) {
	t := s.w.t
	t.Helper()
	if d := diffRefMaps(want, refMap(t, s.replicaDir)); d != "" {
		t.Fatalf("%s: replica refs differ from the origin: %s", what, d)
	}
}

// requireNoPushes fails if the sync made a push of any kind.
func (o rigOutcome) requireNoPushes(t *testing.T, what string) {
	t.Helper()
	if n := len(o.pushes()); n != 0 {
		t.Fatalf("%s: %d push(es) were made (%s), want none", what, n, o.seq())
	}
}

// fsckConnectivity checks that every object the replica's refs reach is present and returns how long
// it took.
func (s *rigSite) fsckConnectivity() time.Duration {
	t := s.w.t
	t.Helper()
	start := time.Now()
	cmd := exec.Command("git", "--git-dir="+s.replicaDir, "fsck", "--connectivity-only", "--no-dangling")
	cmd.Env = []string{"PATH=" + os.Getenv("PATH"), "HOME=" + t.TempDir(), "GIT_CONFIG_NOSYSTEM=1", "GIT_CONFIG_GLOBAL=/dev/null"}
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("replica fsck: %v\n%s", err, out)
	}
	return time.Since(start)
}

// rigNoSecrets fails if any of secrets appears in text. Both credentials travel as Bearer tokens, so
// there is no encoded form to look for.
func rigNoSecrets(t *testing.T, what, text string, secrets ...string) {
	t.Helper()
	for _, s := range secrets {
		if strings.Contains(text, s) {
			t.Errorf("%s contains a credential", what)
		}
	}
}

// rigDiskNeeded is the disk a scenario of this size uses: the origin, the mirror and the replica, a
// restored copy, and headroom. Only the large-repository scenario is big.
func rigDiskNeeded(t *testing.T) int64 {
	t.Helper()
	if !strings.Contains(t.Name(), "LargeRepo") {
		return 2 << 30
	}
	return int64(rigEnvInt(t, "RIG_LARGE_MIB", 512, 1, 65536)) * mebibyte * 4
}
